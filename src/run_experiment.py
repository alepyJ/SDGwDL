from __future__ import annotations
import argparse
import sys
from pathlib import Path

# Permite ejecutar el script directamente desde la raíz del proyecto
# sin instalar el paquete.
if __package__ in {None, ""}:
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from src.data.datasets import load_dataset
from src.data.preprocess import train_test_split_stratified
from src.evaluation.fidelity import correlation_gap, summarize_categorical_similarity, summarize_numeric_similarity
from src.evaluation.privacy import exact_duplicate_rate, nearest_neighbor_privacy_metrics, rare_category_overlap
from src.evaluation.utility import run_tstr_baselines
from src.models.generators import sample_synthetic, train_generator
from src.utils.io import ensure_dir, load_yaml, write_json, write_text
from src.utils.seeds import set_seed

# Convierte opciones como "train" en un número concreto de filas sintéticas.
def _resolve_synthetic_size(setting, train_rows: int) -> int:
    if setting == "train":
        return train_rows
    return int(setting)

# Pipeline principal del experimento:
# carga -> split -> entrenamiento -> generación -> evaluación -> guardado.
def main() -> None:
    parser = argparse.ArgumentParser(description="Run one synthetic tabular experiment from a YAML config.")
    parser.add_argument("config", help="Path to YAML config")
    parser.add_argument("--output-dir", default="results/experiments")
    args = parser.parse_args()

    config = load_yaml(args.config)
    seed = int(config.get("seed", 42))
    # Se fija la semilla para la reproducibilidad del experimento.
    set_seed(seed)

    df, target, spec = load_dataset(config["dataset"])
    target = config.get("target", target)
    split = train_test_split_stratified(
        df,
        target=target,
        test_size=float(config.get("test_size", 0.2)),
        seed=seed,
        id_columns=config.get("id_columns", []),
    )

    experiment_dir = ensure_dir(Path(args.output_dir) / spec.name)
    # Este diccionario centraliza todos los resultados del experimento
    # y sirve luego como base para el reporte.
    summary = {
        "dataset": spec.name,
        "target": target,
        "rows_train": len(split.train_df),
        "rows_test": len(split.test_df),
        "models": {},
    }

    synth_size = _resolve_synthetic_size(config.get("synthetic_size", "train"), len(split.train_df))
    
    # Cada modelo se entrena y evalúa sobre el mismo split
    # para que la comparación sea justa.
    for model_name in config.get("models", ["ctgan", "tvae"]):
        trained = train_generator(
            model_name=model_name,
            train_df=split.train_df,
            seed=seed,
            epochs=int(config.get("epochs", 300)),
        )
        synth_df = sample_synthetic(trained, num_rows=synth_size)

        if target not in synth_df.columns:
            raise ValueError(f"Synthetic data generated by {model_name} does not include target column '{target}'")
        
        # Fidelity mide hasta qué punto los datos sintéticos
        # conservan la estructura estadística de los reales.
        fidelity = {
            "numeric": summarize_numeric_similarity(split.train_df, synth_df, split.numeric_columns),
            "categorical": summarize_categorical_similarity(split.train_df, synth_df, split.categorical_columns + [target]),
            "correlation_gap": correlation_gap(split.train_df, synth_df, split.numeric_columns),
        }

        # Utility estima si los datos sintéticos siguen siendo útiles
        # para una tarea predictiva realista.
        utility = run_tstr_baselines(
            real_train_df=split.train_df,
            synth_train_df=synth_df,
            real_test_df=split.test_df,
            target=target,
            numeric_columns=split.numeric_columns,
            categorical_columns=split.categorical_columns,
            seed=seed,
        )

        # Privacy aproxima el riesgo de filtración o memorización
        # mediante métricas simples basadas en cercanía y duplicados.
        privacy = {
            "nearest_neighbor": nearest_neighbor_privacy_metrics(
                real_train_df=split.train_df,
                synth_df=synth_df,
                numeric_columns=split.numeric_columns,
                categorical_columns=split.categorical_columns,
                sample_size=int(config.get("nn_sample_size", 3000)),
            ),
            "duplicates": exact_duplicate_rate(split.train_df, synth_df),
            "rare_overlap": rare_category_overlap(
                real_train_df=split.train_df,
                synth_df=synth_df,
                categorical_columns=split.categorical_columns,
                rare_threshold=float(config.get("rare_threshold", 0.01)),
            ),
        }

        summary["models"][model_name] = {
            "fidelity": fidelity,
            "utility": utility,
            "privacy": privacy,
        }
        # Se guarda la muestra sintética para poder inspeccionarla
        # sin tener que reentrenar el modelo.
        synth_df.to_csv(experiment_dir / f"{spec.name}_{model_name}_synthetic.csv", index=False)
    
    # summary.json es el artefacto principal para consumir resultados
    # desde reporting o análisis posteriores.
    write_json(experiment_dir / "summary.json", summary)
    write_text(experiment_dir / "README.txt", "Experiment finished successfully. Inspect summary.json for metrics.\n")
    print(f"Experiment written to {experiment_dir}")


if __name__ == "__main__":
    main()
